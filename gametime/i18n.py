def tr(text, language="en", **values):
    translated = text
    if language == "hu":
        translated = HU.get(text, text)
        if translated == text:
            for prefix, target in HU.items():
                if prefix.endswith(": ") and text.startswith(prefix):
                    translated = target + text[len(prefix):]
                    break
    return translated.format(**values) if values else translated
