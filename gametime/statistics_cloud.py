"""Code-only encrypted statistics transport; no account/admin key in the client."""
import base64
import binascii
import hmac
import json
import os
import re
import random
import time
from urllib.error import HTTPError, URLError
from urllib.parse import urlsplit
from urllib.request import Request, HTTPRedirectHandler, build_opener
import zlib

from .statistics_sync import ID, MAX_BYTES, MAX_DEVICES, SyncWorker, validate_snapshot

CLOUD_FORMAT = 'GameTimeMonitor.sync.v2'
SYNC_POLICY = 'event-driven-v2'
SYNC_COOLDOWN = 600
CLOUD_CODE = re.compile(r'[0-9a-f]{32}')
MAX_ENCRYPTED = 512 * 1024
MAX_RESPONSE = 2 * 1024 * 1024
MAX_CLOUD_DEVICES = 20
SERVICE_URL = 'https://jtvdbqwmejrckjejjrdl.supabase.co/functions/v1/statistics-sync'


def new_code():
    return os.urandom(16).hex()


def keys(code):
    if not isinstance(code, str) or not CLOUD_CODE.fullmatch(code):
        raise ValueError('Use a connection code generated by the application.')
    secret = bytes.fromhex(code)
    encryption = hmac.digest(secret, b'GameTimeMonitor/encryption/v1', 'sha256')
    authorization = hmac.digest(secret, b'GameTimeMonitor/authorization/v1', 'sha256').hex()
    return encryption, authorization


def revision(value):
    if not isinstance(value, str) or not re.fullmatch(r'[1-9][0-9]{0,18}', value) or int(value) >= 2**63:
        raise ValueError('Invalid synchronized statistics.')
    return int(value)


def associated_data(device, version):
    if not isinstance(device, str) or not ID.fullmatch(device):
        raise ValueError('Invalid synchronized statistics.')
    revision(version)
    return ('GameTimeMonitor.sync.v1:' + device + ':' + version).encode('ascii')


def seal(snapshot, code):
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    validate_snapshot(snapshot, code)
    raw = json.dumps(snapshot, ensure_ascii=False, allow_nan=False, separators=(',', ':')).encode('utf-8')
    if len(raw) > MAX_BYTES:
        raise ValueError('Statistics history is too large to synchronize.')
    nonce = os.urandom(12)
    aad = associated_data(snapshot['device'], str(snapshot['revision']))
    sealed = b'GTM1' + nonce + AESGCM(keys(code)[0]).encrypt(nonce, zlib.compress(raw), aad)
    if len(sealed) > MAX_ENCRYPTED:
        raise ValueError('Statistics history is too large to synchronize.')
    return base64.b64encode(sealed).decode('ascii')


def unseal(entry, code):
    from cryptography.exceptions import InvalidTag
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    try:
        if not isinstance(entry, dict) or not isinstance(entry['payload'], str) or len(entry['payload']) > 4 * ((MAX_ENCRYPTED + 2)//3):
            raise ValueError()
        aad = associated_data(entry['device'], entry['revision'])
        raw = base64.b64decode(entry['payload'], validate=True)
        if not 32 <= len(raw) <= MAX_ENCRYPTED or raw[:4] != b'GTM1':
            raise ValueError()
        compressed = AESGCM(keys(code)[0]).decrypt(raw[4:16], raw[16:], aad)
        decoder = zlib.decompressobj()
        content = decoder.decompress(compressed, MAX_BYTES + 1)
        if len(content) > MAX_BYTES or not decoder.eof or decoder.unused_data or decoder.unconsumed_tail:
            raise ValueError()
        value = validate_snapshot(json.loads(content.decode('utf-8')), code)
        if value['device'] != entry['device'] or value['revision'] != revision(entry['revision']):
            raise ValueError()
        return value
    except (KeyError, TypeError, ValueError, UnicodeError, binascii.Error, InvalidTag, zlib.error, RecursionError):
        raise ValueError('Invalid synchronized statistics.') from None


class NoRedirect(HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        # Never forward the group credential to a redirect destination.
        return None


class SyncUnavailable(OSError):
    def __init__(self, message, retry_after=0, status=0):
        super().__init__(message)
        self.retry_after=retry_after
        self.status=status


class CloudSyncWorker(SyncWorker):
    failure_message = 'The synchronization service is unavailable. Try syncing manually later.'

    def __init__(self, *, allow_local_http=False):
        super().__init__()
        self.allow_local_http = allow_local_http
        self.published = {}
        self.retries = {}
        self.opener = build_opener(NoRedirect())

    def retry_delay(self, service, code):
        return max(0,self.retries.get((service,code),(0,0))[0]-time.monotonic())

    def failure_warning(self,error):
        if getattr(error,'status',0)==403:
            return 'Cloud sync is not enabled for this connection code. Local statistics are kept.'
        if getattr(error,'status',0) in (429,507):
            return 'The sync limit was reached. Local statistics are kept; try syncing manually later.'
        if getattr(error,'status',0)==426:
            return 'Update Game Time Monitor to synchronize statistics. Local statistics are kept.'
        return self.failure_message

    def request(self, service, code, snapshot, known=None):
        if self.retry_delay(service,code): return False
        return super().request(service, code, (snapshot, dict(known or {})))

    def post(self, service, authorization, body):
        parsed = urlsplit(service)
        local = self.allow_local_http and parsed.hostname in ('127.0.0.1', '::1') and parsed.scheme == 'http'
        if (parsed.scheme != 'https' and not local) or not parsed.hostname or parsed.username or parsed.password or parsed.query or parsed.fragment:
            raise ValueError('Invalid synchronization service address.')
        request = Request(service, data=json.dumps(body, separators=(',', ':')).encode('utf-8'), method='POST',
                          headers={'Authorization': 'Bearer ' + authorization, 'Content-Type': 'application/json',
                                   'Accept': 'application/json', 'User-Agent': 'GameTimeMonitor/statistics-v2',
                                   'X-GameTime-Sync': SYNC_POLICY})
        try:
            with self.opener.open(request, timeout=12) as response:
                deadline=time.monotonic()+20; chunks=[]; size=0
                while True:
                    chunk=response.read1(min(65536,MAX_RESPONSE+1-size))
                    if time.monotonic()>deadline: raise OSError(self.failure_message)
                    if not chunk: break
                    size+=len(chunk)
                    if size>MAX_RESPONSE: raise ValueError('Invalid synchronized statistics.')
                    chunks.append(chunk)
                raw=b''.join(chunks)
                return json.loads(raw.decode('utf-8'))
        except HTTPError as error:
            try:
                header=error.headers.get('Retry-After','')
                delay=min(86400,max(1,int(header))) if re.fullmatch(r'[0-9]{1,8}',header) else 0
                if error.code in (401,403): delay=max(delay,3600)
                if error.code==426: delay=max(delay,86400)
                raise SyncUnavailable(self.failure_message,delay,error.code) from None
            finally: error.close()
        except (URLError, UnicodeError, RecursionError):
            raise OSError(self.failure_message) from None

    def exchange(self, token, job):
        service, code, generation = token
        snapshot, known = job
        authorization = keys(code)[1]
        validate_snapshot(snapshot, code)
        if not isinstance(known, dict) or len(known) > MAX_DEVICES:
            raise ValueError('Invalid synchronized statistics.')
        for device, version in known.items():
            associated_data(device, version)
        if not self.current(token):
            return [], ''
        cache_key = (service, code, snapshot['device'])
        version = str(snapshot['revision'])
        body = dict(format=CLOUD_FORMAT, device=snapshot['device'], revision=version, known=known,
                    payload=None if self.published.get(cache_key) == version else seal(snapshot, code))
        try:
            result = self.post(service, authorization, body)
            if isinstance(result, dict) and result.get('need_upload') is True and body['payload'] is None and self.current(token):
                body['payload'] = seal(snapshot, code)
                result = self.post(service, authorization, body)
        except (OSError,ValueError) as error:
            failures=min(7,self.retries.get((service,code),(0,0))[1]+1)
            delay=max(getattr(error,'retry_after',0),min(3600,30*2**failures)+random.uniform(0,15))
            if len(self.retries)>=8: self.retries.clear()
            self.retries[service,code]=(time.monotonic()+delay,failures)
            raise
        if (not isinstance(result, dict) or result.get('format') != CLOUD_FORMAT or result.get('need_upload') is not False
                or not isinstance(result.get('snapshots'), list) or len(result['snapshots']) > MAX_CLOUD_DEVICES):
            raise ValueError('Invalid synchronized statistics.')
        values, seen = [], set()
        for entry in result['snapshots']:
            value = unseal(entry, code)
            if value['device'] in seen or value['device'] == snapshot['device']:
                raise ValueError('Invalid synchronized statistics.')
            seen.add(value['device']); values.append(value)
        if self.current(token):
            self.retries.pop((service,code),None)
            if len(self.published) >= 8:
                self.published.clear()
            self.published[cache_key] = version
        return values, ''
